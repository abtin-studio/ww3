export function getCalendarLabelFa(round: number): string {
  const idx = Math.max(0, round - 1);
  const m = idx % 12;
  const gregYear = 2027 + Math.floor(idx / 12);
  // Jan 2027 = Dey 1405; Farvardin (m=3) increments Solar Hijri year to 1406!
  const solarYear = 1405 + Math.floor((idx + 9) / 12);
  return `${GREGORIAN_MONTHS_FA[m]} ${gregYear} (${PERSIAN_MONTHS_FA[m]} ${solarYear})`;
}
