export function createInitialMinorNations(): Record<string, MinorNationState> {
  const topo = worldAtlas as unknown as { objects: { countries: unknown } };
  const rawFc = topojson.feature(
    worldAtlas as unknown as Parameters<typeof topojson.feature>[0],
    topo.objects.countries as Parameters<typeof topojson.feature>[1]
  ) as unknown as {
    features: Array<{ id?: string | number; geometry: GeoPermissibleObjects; properties?: { name?: string } }>;
  };

  const out: Record<string, MinorNationState> = {};

  for (const f of rawFc.features) {
    const rawName = f.properties?.name || 'Country';
    const iso = f.id !== undefined ? String(f.id).padStart(3, '0') : `99-${rawName.replace(/\s+/g, '_')}`;
    if (iso === '010' || iso === '260' || MAJOR_ISO_SET.has(iso)) continue;

    const centroid = geoCentroid(f as unknown as GeoPermissibleObjects);
    const coords: [number, number] = [
      Number((centroid[0] || 0).toFixed(2)),
      Number((centroid[1] || 0).toFixed(2)),
    ];

    const curated = CURATED_MINOR_BY_ISO[iso];
    if (curated) {
      out[iso] = {
        id: iso,
        isoNumeric: iso,
        code: curated.code,
        nameFa: curated.nameFa,
        regionFa: curated.regionFa,
        coordinates: coords,
        gdpB: curated.gdpB,
        oilBonus: curated.oilBonus,
        gasBonus: curated.gasBonus,
        foodBonus: curated.foodBonus,
        waterBonus: Math.max(4, curated.foodBonus),
        garrisonPower: curated.garrisonPower,
        stability: 78,
        alignedWith: curated.alignedWith,
        occupierId: null,
        occupationPct: 0,
        conqueredBy: null,
      };
    } else {
      const nameFa = WORLD_EN_TO_FA[rawName] || rawName;
      const isOilState = iso === '024' || iso === '266' || iso === '096' || iso === '728' || iso === '218';
      const isEuropean = coords[1] > 35 && coords[0] > -15 && coords[0] < 32;
      out[iso] = {
        id: iso,
        isoNumeric: iso,
        code: rawName.slice(0, 2).toUpperCase(),
        nameFa,
        regionFa: isEuropean ? 'اروپا' : coords[0] < -30 ? 'قاره آمریکا' : coords[0] > 60 ? 'آسیا-اقیانوسیه' : 'آفریقا و مدیترانه',
        coordinates: coords,
        gdpB: isEuropean ? 160 : 75,
        oilBonus: isOilState ? 14 : 2,
        gasBonus: isOilState ? 8 : 2,
        foodBonus: 6,
        waterBonus: 6,
        garrisonPower: isEuropean ? 135 : 98,
        stability: 76,
        alignedWith: null,
        occupierId: null,
        occupationPct: 0,
        conqueredBy: null,
      };
    }
  }

  return out;
}

